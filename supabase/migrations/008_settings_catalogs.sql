create function public.admin_save_catalog(kind text, target_id text, expected_version integer, new_name text, new_active boolean, new_dunam numeric default null)
returns text language plpgsql security definer set search_path='' as $$
declare tab text; previous jsonb; new_id bigint; cols text; vals text; c record; seq text; active_count integer; duplicate boolean; seq_last bigint;
begin
  perform pg_advisory_xact_lock(84123,2);
  if private.farm_role() is distinct from 'admin' then raise exception 'FORBIDDEN'; end if;
  tab := case kind when 'plots' then 'plots' when 'traders' then 'traders' when 'varieties' then 'varieties' end;
  if tab is null or new_name is null or length(trim(new_name)) not between 1 and 100 or new_active is null
    or (kind='plots' and new_dunam is not null and (new_dunam<0 or new_dunam>1000000 or new_dunam='NaN'::numeric)) then raise exception 'INVALID_CATALOG'; end if;
  execute format('select exists(select 1 from public.%I where lower(trim(farm_name))=lower(trim($1)) and ($2 is null or id::text<>$2))',tab) into duplicate using new_name,target_id;
  if duplicate then raise exception 'DUPLICATE_CATALOG'; end if;
  if target_id is not null then
    execute format('select to_jsonb(t) from public.%I t where t.id::text=$1 for update',tab) into previous using target_id;
    if previous is null or (previous->>'farm_version')::integer is distinct from expected_version then raise exception 'STALE_SETTINGS'; end if;
    if not new_active and (previous->>'farm_active')::boolean then
      execute format('select count(*) from public.%I where farm_active',tab) into active_count;
      if active_count<=1 then raise exception 'LAST_ACTIVE_CATALOG'; end if;
    end if;
    cols := 'farm_name=$1,farm_active=$2,farm_version=farm_version+1';
    if kind='plots' then cols:=cols||',dunam=$3'; end if;
    for c in select column_name from information_schema.columns where table_schema='public' and table_name=tab
      and column_name in ('name','plot_name','variety_name','trader_name','title') and is_generated='NEVER' loop
      cols:=cols||format(',%I=$1',c.column_name);
    end loop;
    execute format('update public.%I set %s where id::text=$4',tab,cols) using trim(new_name),new_active,new_dunam,target_id;
  else
    if expected_version is distinct from 0 then raise exception 'STALE_SETTINGS'; end if;
    execute format('select coalesce(max(id),0)+1 from public.%I',tab) into new_id;
    cols:='id,farm_name,farm_active'; vals:='$1,$2,$3';
    if kind='plots' then cols:=cols||',dunam'; vals:=vals||',$4'; end if;
    for c in select column_name from information_schema.columns where table_schema='public' and table_name=tab
      and column_name in ('name','plot_name','variety_name','trader_name','title') and is_generated='NEVER' loop
      cols:=cols||format(',%I',c.column_name); vals:=vals||',$2';
    end loop;
    execute format('insert into public.%I(%s) overriding system value values(%s)',tab,cols,vals) using new_id,trim(new_name),new_active,new_dunam;
    target_id:=new_id::text;
    seq:=pg_get_serial_sequence('public.'||tab,'id');
    if seq is not null then execute format('select last_value from %s',seq) into seq_last; perform setval(seq::regclass,greatest(new_id,seq_last),true); end if;
  end if;
  insert into public.audit_log(actor_id,action,entity_id,details) values(auth.uid(),'catalog_updated',kind||':'||target_id,
    jsonb_build_object('before',previous,'name',trim(new_name),'active',new_active,'dunam',new_dunam));
  return target_id;
end;
$$;
revoke all on function public.admin_save_catalog(text,text,integer,text,boolean,numeric) from public,anon;
grant execute on function public.admin_save_catalog(text,text,integer,text,boolean,numeric) to authenticated;

